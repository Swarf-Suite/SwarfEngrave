// G-code through CAMCore's post-processor, with SwarfEngrave's name in the header.

import CAMCore
import Foundation

enum GCodeWriter {
    static func files(sheet: Sheet, toolpaths: [Toolpath], machine: MachineProfile, bits: BitSettings, jobName: String) -> [GCodeHub.File] {
        let post = PostProcessor(profile: machine, origin: sheet.workZero.origin(for: sheet.stock),
                                 safeZ: CutPlanner.safeZ(sheet: sheet, bits: bits),
                                 jobName: jobName.isEmpty ? "SwarfEngrave job" : jobName, stockSize: sheet.stock.size)
        return post.process(toolpaths).map { f in
            GCodeHub.File(name: f.name, content: f.content.replacingOccurrences(of: "generated by SwarfPath", with: "generated by SwarfEngrave"))
        }
    }
}
