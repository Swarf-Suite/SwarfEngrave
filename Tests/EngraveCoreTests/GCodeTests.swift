import CAMCore
import Foundation
import Testing
import EngraveCore

@Suite("GCode")
struct GCodeTests {
    static func sheet(zOnTop: Bool = true) -> Sheet {
        var p = DesignObject(name: "P", geometry: .rectangle(width: 20, height: 20, cornerRadius: 0), transform: Transform2D(position: V2(30, 30)))
        p.cut = CutSettings(type: .pocket, depth: 2)
        var v = DesignObject(name: "V", geometry: .star(points: 5, outerRadius: 10, innerRadius: 4), transform: Transform2D(position: V2(70, 70)))
        v.cut = CutSettings(type: .vcarve, depth: 0)
        return Sheet(stock: Stock(width: 100, height: 100, thickness: 10), workZero: WorkZero(corner: .frontLeft, zOnTop: zOnTop), objects: [p, v])
    }

    @Test func singleFileWithHeader() {
        let s = Self.sheet()
        let bits = BitSettings()
        var m = MachineProfile.grbl
        m.splitFilesPerTool = false
        let plan = CutPlanner.plan(sheet: s, bits: bits, machine: m)
        let files = GCodeExport.files(sheet: s, plan: plan, machine: m, bits: bits, jobName: "test")
        #expect(files.count == 1)
        let g = files[0].content
        #expect(!g.isEmpty)
        #expect(g.contains("generated by SwarfEngrave"))
        #expect(!g.contains("SwarfPath"))
        #expect(g.contains("Z0 = TOP of stock"))
        #expect(g.contains("G1"))
        #expect(g.contains("M3"))
        #expect(files[0].name.hasPrefix("test"))
    }

    @Test func oneFilePerBitWhenSplit() {
        let s = Self.sheet(zOnTop: false)
        let bits = BitSettings()
        var m = MachineProfile.grbl
        m.splitFilesPerTool = true
        let plan = CutPlanner.plan(sheet: s, bits: bits, machine: m)
        let files = GCodeExport.files(sheet: s, plan: plan, machine: m, bits: bits, jobName: "split")
        #expect(files.count == 2)
        #expect(files.allSatisfy { $0.content.contains("SPOILBOARD") && $0.content.contains("generated by SwarfEngrave") })
    }

    @Test func emptyPlanGivesNoFiles() {
        let s = Sheet()
        let files = GCodeExport.files(sheet: s, plan: CarvePlan(), machine: .grbl, bits: BitSettings(), jobName: "x")
        #expect(files.isEmpty)
    }
}
